#!/bin/sh
# Точка входа API: контейнер должен быть готов к работе сразу после старта.
#
# 1. Миграции: без них свежий том БД пуст и /readyz отдаёт 503.
# 2. Категории: идемпотентный сид (`--skip-city`), без него справочник категорий пуст,
#    а город и POI — отдельные шаги (нужны файл границы и выгрузка OSM, см. README).
#
# Повторный запуск безопасен: `alembic upgrade head` не применяет уже применённое,
# сид категорий обновляет записи по slug.

set -eu

echo "[entrypoint] применяю миграции Alembic"
alembic upgrade head

if [ "${GEOPULS_AUTO_SEED:-1}" = "1" ]; then
    echo "[entrypoint] сидирую справочник категорий (идемпотентно)"
    python -m geopuls.seed --skip-city
fi

exec "$@"
