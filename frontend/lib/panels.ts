/**
 * Остановить всплытие клика внутри панели.
 *
 * Карта (MapLibre) слушает клики на уровне документа, поэтому клик по панели, лежащей над картой, доходил
 * и до неё: выбор зоны в панели перетирался случайной ячейкой под курсором. Панель — это панель, её клик
 * не должен значить «клик по карте».
 */
export function stopPanelClick(event: { stopPropagation: () => void }): void {
  event.stopPropagation();
}
